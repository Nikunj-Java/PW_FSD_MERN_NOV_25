// ternary Operators
// The ternary operator is a shorthand way of writing an if-else statement.
// It takes three operands: a condition, a value if the condition is true, and a value if the condition is false.
// The syntax is: condition ? value_if_true : value_if_false

let marks= 75;

let result= marks >= 45 ? "Pass": "Fail";
console.log("Result: ", result); // Pass

// Another example
let age=20;
let eligibility= age <= 18 ? "Eligible to vote" : "Not eligible to vote";
console.log("Voting Eligibility: ", eligibility); // Eligible to vote