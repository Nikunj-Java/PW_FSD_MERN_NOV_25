// an arithmetic operator in JavaScript
// is used to perform mathematical operations between numeric values.
// operators: +,-,*,/,%,++,--,**
// 5+2=7
// 5-2=3
// 5*2=10
// 5/2=2.5
// 5%2=1 (modulus operator gives the remainder)
// 5**2=25 (exponentiation operator raises to the power)

let a= 10;
let b= 3;
console.log("Addition: ",a+b); // 13
console.log("Subtraction: ",a-b); // 7
console.log("Multiplication: ",a*b); // 30
console.log("Division: ",a/b);
console.log("Modulus: ",a%b); // 1
console.log("Exponentiation: ",a**b); // 1000  its a power b