//lastIndexOf() finds the last position (index) where a value appears 
// in an array or string.

let fruits = ["apple", "banana", "mango", "banana", "orange"];

console.log(fruits.lastIndexOf("banana"));
console.log(fruits.lastIndexOf("apple"));
console.log(fruits.lastIndexOf("grape"));

//last indexOf in String
let text= "Hello World Hello";
console.log(text.lastIndexOf("Hello"));

//indexOf() finds the position (index) of the first occurrence of a value
//  in an array or string.
console.log(fruits.indexOf("banana"));
console.log(text.indexOf("Hello"));